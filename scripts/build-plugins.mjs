// Builds the installable packages from the bridge, so they always carry the same hooks as `lotse connect`:
//   plugins/marshal/   Claude Code plugin (hooks, the connect skill, the built bridge, a vendored copy of ws)
//   hooks/hooks.json   Gemini CLI extension hooks (gemini-extension.json sits at the repo root)
// Usage, from the repo root, after `npm run build` in bridge/:  node scripts/build-plugins.mjs
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "bridge", "dist");
if (!existsSync(join(dist, "cli.js"))) throw new Error("bridge/dist/cli.js is missing: run `npm run build` in bridge/ first");

const load = (f) => import(pathToFileURL(join(dist, f)).href);
const { buildHookSettings } = await load("install.js");
const { buildToolHooks } = await load("install-tools.js");
const bridge = JSON.parse(readFileSync(join(root, "bridge", "package.json"), "utf8"));
const lock = JSON.parse(readFileSync(join(root, "bridge", "package-lock.json"), "utf8"));
const json = (file, value) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(value, null, 2) + "\n");
};

// ---- Claude Code plugin ----
const plugin = join(root, "plugins", "marshal");
rmSync(join(plugin, "dist"), { recursive: true, force: true });
cpSync(dist, join(plugin, "dist"), { recursive: true, filter: (src) => !/\.(d\.ts|map)$/.test(src) });

// The bridge server needs `ws` (the hooks need nothing). It is vendored into the plugin, so installing the plugin
// downloads nothing: no package-lock.json here, because with one Claude Code would run an npm install.
const ws = lock.packages["node_modules/ws"];
const wsDir = join(plugin, "node_modules", "ws");
rmSync(join(plugin, "node_modules"), { recursive: true, force: true });
rmSync(join(plugin, "package-lock.json"), { force: true });
cpSync(join(root, "bridge", "node_modules", "ws"), wsDir, { recursive: true });
if (JSON.parse(readFileSync(join(wsDir, "package.json"), "utf8")).version !== ws.version) throw new Error("bridge/node_modules/ws does not match the lock; run npm ci in bridge/");
json(join(plugin, "package.json"), {
  name: "marshal-plugin",
  version: bridge.version,
  private: true,
  license: "Apache-2.0",
  type: "module",
  engines: bridge.engines,
  bundleDependencies: ["ws"],
  bundledVersions: { ws: ws.version },
});

// Same handlers as `connect` writes into ~/.claude/settings.json, minus the statusLine (plugins cannot set one).
const claudeCmd = 'node "${CLAUDE_PLUGIN_ROOT}/dist/cli.js"';
json(join(plugin, "hooks", "hooks.json"), { hooks: buildHookSettings(claudeCmd, "command").hooks });

// Muse reads this same marketplace and would import the Claude manifest, but it skips the Claude Stop hook
// (`asyncRewake`) and would report as Claude. A native Muse manifest next to it carries Muse's own events.
const { musePluginManifest } = await load("muse-plugin.js");
// Muse wants a separate source file per hook, so each hook gets a two-line entry file calling the shim directly.
const PLACEHOLDER = "@@CLI@@";
const muse = musePluginManifest(`node "${PLACEHOLDER}"`);
rmSync(join(plugin, "muse-hooks"), { recursive: true, force: true });
mkdirSync(join(plugin, "muse-hooks"), { recursive: true });
for (const h of muse.capabilities.hooks) {
  const args = h.command.slice(2); // after node and the cli: ["hook", "--source", "muse", ...]
  if (h.command[1] !== PLACEHOLDER || args[0] !== "hook") throw new Error(`unexpected Muse hook command for ${h.id}`);
  writeFileSync(join(plugin, "muse-hooks", `${h.id}.mjs`),
    `// Muse ${h.event} hook of Marshal (generated by scripts/build-plugins.mjs).\nimport { runHook } from "../dist/hook-cli.js";\nvoid runHook(${JSON.stringify(args.slice(1))});\n`);
  h.command = ["node", `muse-hooks/${h.id}.mjs`];
}
const claudeManifest = JSON.parse(readFileSync(join(plugin, ".claude-plugin", "plugin.json"), "utf8"));
json(join(plugin, ".muse-plugin", "plugin.json"), { ...muse, name: "marshal", version: claudeManifest.version, description: claudeManifest.description.replace("your Claude Code sessions", "your Muse sessions") });

// Codex reads this marketplace too and probes `.codex-plugin` before `.claude-plugin`. Its default hooks path is
// the same `hooks/hooks.json` as Claude's, so the Codex manifest points to its own file. Codex passes the plugin
// folder only as the environment variable PLUGIN_ROOT and runs hooks through cmd.exe on Windows, hence the
// separate `commandWindows`.
const CODEX = "@@CODEX@@";
const codexHooks = buildToolHooks("codex", CODEX);
for (const groups of Object.values(codexHooks.hooks)) {
  for (const g of groups) {
    for (const h of g.hooks) {
      if (!h.command.startsWith(`${CODEX} hook `)) throw new Error("unexpected Codex hook command");
      const args = h.command.slice(CODEX.length);
      h.command = `node "$PLUGIN_ROOT/dist/cli.js"${args}`;
      h.commandWindows = `node "%PLUGIN_ROOT%\\dist\\cli.js"${args}`;
    }
  }
}
json(join(plugin, "codex", "hooks.json"), codexHooks);
json(join(plugin, ".codex-plugin", "plugin.json"), {
  name: "marshal",
  version: claudeManifest.version,
  description: claudeManifest.description.replace("your Claude Code sessions", "your Codex sessions"),
  author: claudeManifest.author,
  homepage: claudeManifest.homepage,
  repository: claudeManifest.repository,
  license: claudeManifest.license,
  hooks: "./codex/hooks.json",
});

// ---- Gemini CLI extension (the repo root is the extension) ----
const geminiCmd = 'node "${extensionPath}/plugins/marshal/dist/cli.js"';
json(join(root, "hooks", "hooks.json"), buildToolHooks("gemini", geminiCmd));

console.log("written: plugins/marshal (dist, node_modules/ws, package.json, hooks/hooks.json), hooks/hooks.json");
