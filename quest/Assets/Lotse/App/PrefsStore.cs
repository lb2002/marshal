using UnityEngine;

namespace Lotse.App
{
    /// <summary>IKeyValueStore on PlayerPrefs: the recent bridge addresses and their session tokens survive restarts.</summary>
    public sealed class PrefsStore : IKeyValueStore
    {
        public string Get(string key) => PlayerPrefs.HasKey(key) ? PlayerPrefs.GetString(key) : null;

        public void Set(string key, string value)
        {
            PlayerPrefs.SetString(key, value);
            PlayerPrefs.Save();
        }

        public void Delete(string key)
        {
            PlayerPrefs.DeleteKey(key);
            PlayerPrefs.Save();
        }
    }
}
