// OpenCode has no command hooks; it loads JS plugins (V2 plugin API, opencode 2.x) from `<config>/opencode/plugins/<name>/index.js`
// (all sessions) or `<project>/.opencode/plugins/<name>/index.js`. Marshal writes one small plugin there that runs the
// same hook shim as every other agent: `"<node>" "<cli.js>" hook --source opencode [--event …]`, with a small JSON on
// stdin (adapters.ts maps it onto Claude's hook names). This file only generates its text; opencode-install.ts writes it.
//
// What the plugin does, in OpenCode's own hooks:
// - `tool.execute.before`: PreToolUse (waits up to 3 s). A deny from the shim (halt-all) throws, which blocks the call.
// - `permission.evaluate`, only when OpenCode would ask: PermissionRequest (waits up to 105 s; the bridge holds 90 s,
//   the shim 100 s). An exact allow sets the effect `allow`, a deny `deny` with its message; anything else leaves the
//   effect alone, so OpenCode asks as usual. Never throws there (a rejection is an unhandled defect in OpenCode).
// - `tool.execute.after` and the session events: observe only, fire and forget (2 s).

import { PRODUCT_NAME } from "./product.js";

/** The first line of every plugin Marshal writes; a file that starts with it looks like Marshal's. */
export const OPENCODE_PLUGIN_MARKER = `// ${PRODUCT_NAME} plugin for OpenCode, generated by ${PRODUCT_NAME}.`;

/** The plugin's folder name (and id) under `plugins/`. */
export const OPENCODE_PLUGIN_NAME = "marshal";

/** The plugin file for this node and this cli.js. Pure: the same paths give the same text, byte for byte. */
export function opencodePluginSource(nodePath: string, cliPath: string): string {
  return `${OPENCODE_PLUGIN_MARKER} Do not edit: lotse connect replaces it, lotse disconnect removes it.
// For every OpenCode session, tool call and permission request it runs the ${PRODUCT_NAME} hook (the node and cli.js
// below) with a small JSON on stdin: {event, sessionID, cwd, tool?, input?, status?, action?, resources?, error?}.
// That hook forwards it to the ${PRODUCT_NAME} bridge on this computer (127.0.0.1) and prints the headset's answer.
// When OpenCode would ask for a permission, the headset can allow or deny it; without an answer OpenCode asks as usual.
// While all agents are halted in the headset, tool calls are blocked.
import { spawn } from "node:child_process";

const NODE = ${JSON.stringify(nodePath)};
const CLI = ${JSON.stringify(cliPath)};

/** Runs the hook with \`payload\` on stdin; resolves its parsed stdout, or null (no answer, timeout, any error). */
function hook(payload, event, ms) {
  return new Promise((resolve) => {
    let settled = false;
    let child = null;
    let out = "";
    const done = (v) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve(v);
    };
    const timer = setTimeout(() => {
      try {
        if (child) child.kill();
      } catch {}
      done(null);
    }, ms);
    try {
      const args = [CLI, "hook", "--source", "opencode", ...(event ? ["--event", event] : [])];
      child = spawn(NODE, args, { stdio: ["pipe", "pipe", "ignore"], windowsHide: true });
      child.on("error", () => done(null));
      child.stdout.setEncoding("utf8");
      child.stdout.on("data", (c) => {
        out += c;
      });
      child.on("close", () => {
        try {
          const v = out.trim() === "" ? null : JSON.parse(out);
          done(v !== null && typeof v === "object" && !Array.isArray(v) ? v : null);
        } catch {
          done(null);
        }
      });
      child.stdin.on("error", () => {});
      child.stdin.end(JSON.stringify(payload));
    } catch {
      done(null);
    }
  });
}

const isDeny = (r) => r !== null && r.decision === "deny";
const denyText = (r) => (typeof r.message === "string" && r.message.trim() !== "" ? r.message : "Denied in ${PRODUCT_NAME}.");

export default {
  id: ${JSON.stringify(OPENCODE_PLUGIN_NAME)},
  async setup(ctx) {
    const home = ctx.location.directory;
    const dirs = new Map(); // sessionID -> its folder
    const calls = new Map(); // tool call id -> { tool, input }, for the permission request of that call
    const base = (event, sessionID) => {
      if (!dirs.has(sessionID)) dirs.set(sessionID, home);
      return { event, sessionID, cwd: dirs.get(sessionID) };
    };
    const send = (payload) => {
      void hook(payload, null, 2000);
    };

    ctx.tool.hook("execute.before", async (e) => {
      let r = null;
      try {
        calls.set(e.id, { tool: e.tool, input: e.input });
        if (calls.size > 200) calls.delete(calls.keys().next().value);
        r = await hook({ ...base("PreToolUse", e.sessionID), tool: e.tool, input: e.input }, "PreToolUse", 3000);
      } catch {
        r = null;
      }
      if (isDeny(r)) throw new Error(denyText(r));
    });

    ctx.tool.hook("execute.after", async (e) => {
      try {
        calls.delete(e.id);
        const failed = e.status === "error";
        const error = failed ? String(e.error && e.error.message ? e.error.message : e.error) : undefined;
        send({ ...base(failed ? "PostToolUseFailure" : "PostToolUse", e.sessionID), tool: e.tool, input: e.input, status: e.status, ...(failed ? { error } : {}) });
      } catch {}
    });

    ctx.permission.hook("evaluate", async (e) => {
      try {
        if (e.effect !== "ask") return; // only what OpenCode would ask about goes to the headset
        const call = e.source && e.source.type === "tool" ? calls.get(e.source.id) : undefined;
        const payload = { ...base("PermissionRequest", e.sessionID), action: e.action, resources: e.resources, ...(call ? { tool: call.tool, input: call.input } : {}) };
        const r = await hook(payload, "PermissionRequest", 105000);
        if (r !== null && r.decision === "allow") e.effect = "allow";
        else if (isDeny(r)) {
          e.effect = "deny";
          e.message = denyText(r);
        }
      } catch {}
    });

    const stop = new AbortController();
    const listen = (type, on) => {
      void (async () => {
        try {
          for await (const ev of ctx.event.subscribe({ types: [type], signal: stop.signal })) {
            try {
              if (ev && ev.data && typeof ev.data.sessionID === "string") on(ev.data);
            } catch {}
          }
        } catch {}
      })();
    };
    listen("session.created", (d) => {
      if (d.location && typeof d.location.directory === "string") dirs.set(d.sessionID, d.location.directory);
      send(base("SessionStart", d.sessionID));
    });
    listen("session.status", (d) => {
      if (d.status === "idle") send(base("Stop", d.sessionID));
    });
    listen("session.execution.failed", (d) => {
      send({ ...base("StopFailure", d.sessionID), error: String(d.error && d.error.message ? d.error.message : d.error) });
    });

    return () => {
      stop.abort();
      for (const sessionID of dirs.keys()) send(base("SessionEnd", sessionID));
    };
  },
};
`;
}
